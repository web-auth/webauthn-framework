<?php

declare(strict_types=1);

namespace Webauthn\Bundle\Security\Guesser;

use function count;
use Symfony\Component\HttpFoundation\Request;
use Symfony\Component\Serializer\Encoder\JsonEncoder;
use Symfony\Component\Serializer\SerializerInterface;
use Symfony\Component\Validator\Validator\ValidatorInterface;
use Webauthn\Bundle\Dto\ServerPublicKeyCredentialCreationOptionsRequest;
use Webauthn\Bundle\Exception\MissingUserEntityException;
use Webauthn\Bundle\Repository\CanGenerateUserEntity;
use Webauthn\Bundle\Repository\PublicKeyCredentialUserEntityRepositoryInterface;
use Webauthn\Exception\InvalidDataException;
use Webauthn\PublicKeyCredentialUserEntity;

/**
 * Guesses the user entity of a registration from the username and display name of the request body.
 *
 * The request is not authenticated, so its body never selects an existing account: the creation options, and the
 * credential registered with them, would otherwise be bound to the account of whoever the client names. The entity is
 * always generated by the user entity repository, even when the username is already taken, and a generated entity
 * whose user handle already belongs to a user is refused. The firewall refuses a taken username when the registration
 * completes.
 *
 * @see CanGenerateUserEntity::generateUserEntity()
 */
final readonly class RequestBodyUserEntityGuesser implements UserEntityGuesser
{
    public function __construct(
        private SerializerInterface $serializer,
        private ValidatorInterface $validator,
        private PublicKeyCredentialUserEntityRepositoryInterface $userEntityRepository,
    ) {
    }

    public function findUserEntity(Request $request): PublicKeyCredentialUserEntity
    {
        $format = $request->getContentTypeFormat();
        $format === 'json' || throw InvalidDataException::create($format, 'Only JSON content type allowed');
        $content = $request->getContent();

        /** @var ServerPublicKeyCredentialCreationOptionsRequest $dto */
        $dto = $this->serializer->deserialize(
            $content,
            ServerPublicKeyCredentialCreationOptionsRequest::class,
            JsonEncoder::FORMAT
        );
        $errors = $this->validator->validate($dto);

        if (count($errors) > 0) {
            $messages = [];
            foreach ($errors as $error) {
                $messages[] = $error->getPropertyPath() . ': ' . $error->getMessage();
            }
            throw InvalidDataException::create(null, implode("\n", $messages));
        }

        if (! $this->userEntityRepository instanceof CanGenerateUserEntity) {
            throw MissingUserEntityException::create('Unable to find the user entity');
        }
        $userEntity = $this->userEntityRepository->generateUserEntity($dto->username, $dto->displayName);
        $this->userEntityRepository->findOneByUserHandle($userEntity->id) === null || throw InvalidDataException::create(
            $userEntity,
            'The generated user handle is already in use'
        );

        return $userEntity;
    }
}
